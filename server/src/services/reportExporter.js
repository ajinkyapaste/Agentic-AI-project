/**
 * Report Generation Suite
 * Exports Executive Summaries, Analytics Tables & Raw Data in PDF, Excel, and CSV.
 */

const PDFDocument = require('pdfkit');
const ExcelJS = require('exceljs');
const { getExecutiveKpis, getSeasonalAnalytics, getProductAnalytics, getCategoryAnalytics } = require('./statisticalEngine');
const { generateExecutiveInsights } = require('./aiInsightsEngine');

/**
 * Generate PDF Executive Intelligence Report
 */
function generatePdfReport(dataset, records, stream) {
  const doc = new PDFDocument({ margin: 40, size: 'A4' });
  doc.pipe(stream);

  const kpis = getExecutiveKpis(records);
  const seasonal = getSeasonalAnalytics(records);
  const products = getProductAnalytics(records);
  const categories = getCategoryAnalytics(records);
  const insights = generateExecutiveInsights(records);

  // Header Banner
  doc.rect(0, 0, 595, 75).fill('#0f172a');
  doc.fillColor('#ffffff').fontSize(22).font('Helvetica-Bold').text('SALES INTELLIGENCE EXECUTIVE REPORT', 40, 22);
  doc.fontSize(10).font('Helvetica').fillColor('#94a3b8').text(`Dataset: ${dataset.name} | Generated: ${new Date().toLocaleDateString()}`, 40, 48);

  doc.moveDown(3);

  // 1. Executive KPIs Summary Cards
  doc.fillColor('#0f172a').fontSize(14).font('Helvetica-Bold').text('1. Executive Financial & Sales KPIs', 40, 95);
  doc.rect(40, 115, 515, 65).fillAndStroke('#f8fafc', '#e2e8f0');

  const cardWidth = 515 / 4;
  const kpiItems = [
    { label: 'Total Revenue', val: `$${kpis.totalRevenue.toLocaleString()}` },
    { label: 'Units Sold', val: `${kpis.totalUnits.toLocaleString()}` },
    { label: 'Gross Margin', val: `${kpis.grossMargin}%` },
    { label: 'Active SKUs', val: `${kpis.activeProducts}` },
  ];

  kpiItems.forEach((item, idx) => {
    const x = 40 + idx * cardWidth + 10;
    doc.fillColor('#64748b').fontSize(8).font('Helvetica').text(item.label.toUpperCase(), x, 125);
    doc.fillColor('#0f172a').fontSize(13).font('Helvetica-Bold').text(item.val, x, 142);
  });

  // 2. AI Executive Insights & Strategy
  let yPos = 195;
  doc.fillColor('#0f172a').fontSize(14).font('Helvetica-Bold').text('2. AI-Generated Business Insights', 40, yPos);
  yPos += 20;

  insights.slice(0, 3).forEach((ins) => {
    doc.rect(40, yPos, 515, 45).fillAndStroke('#ffffff', '#cbd5e1');
    doc.fillColor('#2563eb').fontSize(9).font('Helvetica-Bold').text(`[${ins.type}] ${ins.title}`, 50, yPos + 8);
    doc.fillColor('#334155').fontSize(8).font('Helvetica').text(ins.summary, 50, yPos + 22, { width: 495 });
    yPos += 52;
  });

  // 3. Seasonal Demand Breakdown Table
  yPos += 10;
  doc.fillColor('#0f172a').fontSize(14).font('Helvetica-Bold').text('3. Seasonal Demand Breakdown', 40, yPos);
  yPos += 20;

  // Table Header
  doc.rect(40, yPos, 515, 20).fill('#1e293b');
  doc.fillColor('#ffffff').fontSize(9).font('Helvetica-Bold');
  doc.text('Season', 50, yPos + 5);
  doc.text('Revenue ($)', 160, yPos + 5);
  doc.text('Units', 260, yPos + 5);
  doc.text('Share (%)', 350, yPos + 5);
  doc.text('Seasonal Index', 440, yPos + 5);
  yPos += 20;

  seasonal.breakdown.forEach((s, idx) => {
    const rowBg = idx % 2 === 0 ? '#f8fafc' : '#ffffff';
    doc.rect(40, yPos, 515, 18).fill(rowBg);
    doc.fillColor('#1e293b').fontSize(8).font('Helvetica');
    doc.text(s.season, 50, yPos + 5);
    doc.text(`$${s.revenue.toLocaleString()}`, 160, yPos + 5);
    doc.text(`${s.units.toLocaleString()}`, 260, yPos + 5);
    doc.text(`${s.revenueShare}%`, 350, yPos + 5);
    doc.text(`${s.seasonalIndex}`, 440, yPos + 5);
    yPos += 18;
  });

  // 4. Top Performing Products
  yPos += 15;
  doc.fillColor('#0f172a').fontSize(14).font('Helvetica-Bold').text('4. Top Performing SKUs by Revenue', 40, yPos);
  yPos += 20;

  doc.rect(40, yPos, 515, 20).fill('#1e293b');
  doc.fillColor('#ffffff').fontSize(9).font('Helvetica-Bold');
  doc.text('Product Name', 50, yPos + 5);
  doc.text('Category', 220, yPos + 5);
  doc.text('Sales (Units)', 330, yPos + 5);
  doc.text('Revenue ($)', 430, yPos + 5);
  yPos += 20;

  products.topByRevenue.slice(0, 5).forEach((p, idx) => {
    const rowBg = idx % 2 === 0 ? '#f8fafc' : '#ffffff';
    doc.rect(40, yPos, 515, 18).fill(rowBg);
    doc.fillColor('#1e293b').fontSize(8).font('Helvetica');
    doc.text(p.productName, 50, yPos + 5, { width: 160, ellipsis: true });
    doc.text(p.category, 220, yPos + 5);
    doc.text(`${p.totalSales.toLocaleString()}`, 330, yPos + 5);
    doc.text(`$${p.totalRevenue.toLocaleString()}`, 430, yPos + 5);
    yPos += 18;
  });

  // Footer
  doc.fillColor('#94a3b8').fontSize(8).font('Helvetica').text('Generated by Sales Intelligence & AI Analytics Platform — Confidential', 40, 780, { align: 'center' });

  doc.end();
}

/**
 * Generate Comprehensive Excel Report (Multi-tab Workbook)
 */
async function generateExcelReport(dataset, records) {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'Sales Intelligence Platform';
  workbook.created = new Date();

  const kpis = getExecutiveKpis(records);
  const seasonal = getSeasonalAnalytics(records);
  const products = getProductAnalytics(records);
  const categories = getCategoryAnalytics(records);

  // Tab 1: Executive Summary
  const summarySheet = workbook.addWorksheet('Executive Summary');
  summarySheet.columns = [
    { header: 'Metric', key: 'metric', width: 30 },
    { header: 'Value', key: 'value', width: 30 },
  ];
  summarySheet.addRow({ metric: 'Dataset Name', value: dataset.name });
  summarySheet.addRow({ metric: 'Total Revenue ($)', value: kpis.totalRevenue });
  summarySheet.addRow({ metric: 'Total Units Sold', value: kpis.totalUnits });
  summarySheet.addRow({ metric: 'Total Cost ($)', value: kpis.totalCost });
  summarySheet.addRow({ metric: 'Gross Profit ($)', value: kpis.grossProfit });
  summarySheet.addRow({ metric: 'Gross Margin (%)', value: kpis.grossMargin });
  summarySheet.addRow({ metric: 'Average Order Value ($)', value: kpis.avgOrderValue });
  summarySheet.addRow({ metric: 'Active Products', value: kpis.activeProducts });
  summarySheet.addRow({ metric: 'Active Categories', value: kpis.activeCategories });
  summarySheet.addRow({ metric: 'Peak Demand Season', value: seasonal.peakSeason });
  summarySheet.getRow(1).font = { bold: true };

  // Tab 2: Raw Records
  const recordSheet = workbook.addWorksheet('Raw Sales Records');
  recordSheet.columns = [
    { header: 'Product ID', key: 'productId', width: 14 },
    { header: 'Product Name', key: 'productName', width: 25 },
    { header: 'Category', key: 'category', width: 18 },
    { header: 'Month', key: 'month', width: 14 },
    { header: 'Quarter', key: 'quarter', width: 10 },
    { header: 'Season', key: 'season', width: 14 },
    { header: 'Festival', key: 'festival', width: 16 },
    { header: 'Price ($)', key: 'price', width: 12 },
    { header: 'Cost ($)', key: 'cost', width: 12 },
    { header: 'Current Stock', key: 'stock', width: 14 },
    { header: 'Monthly Sales', key: 'monthlySales', width: 14 },
    { header: 'Revenue ($)', key: 'revenue', width: 16 },
    { header: 'Profit ($)', key: 'profit', width: 14 },
    { header: 'Margin %', key: 'marginPercentage', width: 12 },
    { header: 'Customer Segment', key: 'customerSegment', width: 16 },
  ];
  recordSheet.getRow(1).font = { bold: true };

  records.forEach((r) => {
    recordSheet.addRow({
      productId: r.productId,
      productName: r.productName,
      category: r.category,
      month: r.month,
      quarter: r.quarter,
      season: r.season,
      festival: r.festival,
      price: r.price,
      cost: r.cost,
      stock: r.stock,
      monthlySales: r.monthlySales,
      revenue: r.revenue,
      profit: r.profit,
      marginPercentage: r.marginPercentage,
      customerSegment: r.customerSegment,
    });
  });

  // Tab 3: Seasonal Analysis
  const seasonalSheet = workbook.addWorksheet('Seasonal Breakdown');
  seasonalSheet.columns = [
    { header: 'Season', key: 'season', width: 18 },
    { header: 'Revenue ($)', key: 'revenue', width: 16 },
    { header: 'Units Sold', key: 'units', width: 14 },
    { header: 'Profit ($)', key: 'profit', width: 14 },
    { header: 'Margin (%)', key: 'margin', width: 14 },
    { header: 'Revenue Share (%)', key: 'revenueShare', width: 18 },
    { header: 'Seasonal Index', key: 'seasonalIndex', width: 16 },
  ];
  seasonalSheet.getRow(1).font = { bold: true };
  seasonal.breakdown.forEach((s) => seasonalSheet.addRow(s));

  // Tab 4: Category Analysis
  const categorySheet = workbook.addWorksheet('Category Performance');
  categorySheet.columns = [
    { header: 'Category', key: 'category', width: 20 },
    { header: 'Revenue ($)', key: 'revenue', width: 16 },
    { header: 'Units Sold', key: 'units', width: 14 },
    { header: 'Profit ($)', key: 'profit', width: 14 },
    { header: 'Margin (%)', key: 'margin', width: 14 },
    { header: 'Market Share (%)', key: 'marketShare', width: 16 },
  ];
  categorySheet.getRow(1).font = { bold: true };
  categories.categories.forEach((c) => categorySheet.addRow(c));

  return workbook;
}

/**
 * Generate CSV string from records
 */
function generateCsvData(records) {
  if (!records.length) return '';
  const headers = [
    'Product_ID', 'Product_Name', 'Category', 'Month', 'Quarter', 'Season',
    'Festival', 'Price', 'Cost', 'Stock', 'Monthly_Sales', 'Revenue',
    'Profit', 'Margin_%', 'Customer_Segment'
  ];

  const rows = records.map((r) => [
    `"${r.productId || ''}"`,
    `"${(r.productName || '').replace(/"/g, '""')}"`,
    `"${(r.category || '').replace(/"/g, '""')}"`,
    `"${r.month || ''}"`,
    `"${r.quarter || ''}"`,
    `"${r.season || ''}"`,
    `"${r.festival || ''}"`,
    r.price || 0,
    r.cost || 0,
    r.stock || 0,
    r.monthlySales || 0,
    r.revenue || 0,
    r.profit || 0,
    r.marginPercentage || 0,
    `"${r.customerSegment || ''}"`,
  ].join(','));

  return [headers.join(','), ...rows].join('\n');
}

module.exports = {
  generatePdfReport,
  generateExcelReport,
  generateCsvData,
};

